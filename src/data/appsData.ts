// Section 8 logic implementation
export function recommendApps(
  audience: 'general' | 'developer' | 'both' | null,
  devField: string | null
): string[] {
  const bundle = new Set<string>();

  if (!audience) return Array.from(bundle);

  if (audience === 'general' || audience === 'both') {
    ['chrome', 'libreoffice', 'pdf_reader', 'whatsapp', 'zoom', 'vlc', 'sevenzip'].forEach(
      (id) => bundle.add(id)
    );
  }

  if (audience === 'developer' || audience === 'both') {
    ['git', 'vscode'].forEach((id) => bundle.add(id));

    switch (devField) {
      case 'web_dev':
        ['nodejs', 'github_desktop', 'postman'].forEach((id) => bundle.add(id));
        break;
      case 'ai_ml':
        ['python', 'anaconda', 'jupyter'].forEach((id) => bundle.add(id));
        break;
      case 'app_dev':
        ['android_studio', 'nodejs'].forEach((id) => bundle.add(id));
        break;
      case 'data_science':
        ['python', 'anaconda', 'jupyter'].forEach((id) => bundle.add(id));
        break;
      case 'cybersecurity':
        ['wireshark', 'python'].forEach((id) => bundle.add(id));
        break;
      case 'not_sure':
      default:
        ['python', 'nodejs', 'postman'].forEach((id) => bundle.add(id));
        break;
    }
  }

  return Array.from(bundle);
}
